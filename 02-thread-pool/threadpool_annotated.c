/* ---------------------------------------------------------------------------
 * 第 2 部分：两个链表宏
 *
 * 先解释"宏"：
 *   #define 是"文字替换"。编译器在真正编译之前，会把代码里所有出现
 *   宏名字的地方，原样替换成宏定义的内容。
 *   它不是函数调用，没有函数调用的开销，也没有类型检查。
 * ------------------------------------------------------------------------- */

/* ---------------------------------------------------------------------------
 * LIST_INSERT(item, list) —— 把一个节点插到双向链表的【头部】
 *
 * 【什么是双向链表】
 *   一条链子，每一环（节点）都记着"我前一个是谁"（prev）和"我后一个是谁"（next）。
 *   好处：知道任意一环，就能往前往后走，也能在 O(1) 时间内把它摘下来。
 *   这份代码里，nTask 和 nWorker 都是靠 prev/next 串成链的。
 *
 * 【为什么要包一层 do { ... } while(0)】
 *   因为宏是纯文字替换。如果写成
 *       #define LIST_INSERT(item,list)  a; b; c;
 *   那么当你在 if 里用：
 *       if (条件) LIST_INSERT(x, y);
 *   展开后是：
 *       if (条件) a; b; c;     ← 只有 a 受 if 控制，b 和 c 无条件执行！
 *   这是 C 语言里最经典的坑之一。
 *   而 do { ... } while(0) 整体在语法上算【一条语句】，
 *   后面那个分号正好接上，if 就能完整地控制全部三句话。
 *   编译器会把 do{...}while(0) 优化掉，不会真的产生循环。
 * ------------------------------------------------------------------------- */
#define LIST_INSERT(item, list) do {	\
	item->prev = NULL;					\
	item->next = list;					\
	if ((list) != NULL) (list)->prev = item; \
	(list) = item;						\
} while(0)
/*  \  （行尾反斜杠）是"续行符"：
 *     作用是把下面一行接到这一行后面，让宏定义能写好几行。
 *     注意 \ 后面不能有任何空格，否则续行失败，报错很莫名其妙。
 *
 *  逐句解释，假设 item 是新节点，list 是当前链表头（可能是 NULL）：
 *
 *  ① item->prev = NULL;
 *     "->" 是"取指针指向的结构的成员"。
 *     新节点插在头部，前面没东西，所以 prev 空。
 *
 *  ② item->next = list;
 *     新节点的下一个 = 原来的链表头。
 *     （如果 list 是 NULL，就是空链表，那 item->next 也是 NULL。）
 *
 *  ③ if ((list) != NULL) (list)->prev = item;
 *     原来的链表头从此不再是头了，它的"前一个"应该变成新节点。
 *     必须判空：链表原本是空的，list 为 NULL，解引用空指针会直接崩溃。
 *     外面多包一层括号 (list) 是防御性的写法：
 *     如果调用者传进来的是 list->next 这种带运算的表达式，不加括号会算错。
 *
 *  ④ (list) = item;
 *     把链表头指针指向新节点。
 *     注意"="左边是 (list)，不是 list 的副本。
 *     因为宏是文字替换，如果你调用 LIST_INSERT(w, pool->workers)，
 *     这一句就会展开成   pool->workers = w;   ——直接改到了经理身上的字段。
 *     这正是宏能"修改调用者变量"的原理，也是它危险的地方。
 * ------------------------------------------------------------------------- */


/* ---------------------------------------------------------------------------
 * LIST_REMOVE(item, list) —— 把节点 item 从链表里摘下来
 *
 * 摘链表的本质是一句话：
 *   "让我的前一个直接连到我的后一个，把我跳过。"
 *   相当于队伍里有人要退出，他前面的人直接去牵他后面的人的手。
 * ------------------------------------------------------------------------- */
#define LIST_REMOVE(item, list) do {	\
	if (item->prev != NULL) item->prev->next = item->next; \
	if (item->next != NULL) item->next->prev = item->prev; \
	if (list == item) list = item->next; 					\
	item->prev = item->next = NULL;							\
} while(0)
/*  ① 如果 item 前面有人，让前一个的 next 跳过 item，指到 item 后面。
 *     如果 item->prev 是 NULL，说明 item 本来就是链表头，没人需要跳过它。
 *
 *  ② 如果 item 后面有人，让后一个的 prev 跳过 item，指到 item 前面。
 *     对称操作，理由同上。
 *
 *  ③ 如果 item 正好是链表头，那链表头要往后挪一格。
 *     （如果 item 是唯一的节点，item->next 是 NULL，链表头就变成 NULL，链表变空。
 *      这正是工人们判断"有没有任务"的依据。）
 *
 *  ④ item->prev = item->next = NULL;
 *     连等号从右往左算：先 item->next = NULL，再 item->prev = NULL。
 *     把摘下来的节点自己的指针清干净，避免它偷偷还指向旧链表里的其他节点，
 *     否则以后误用它就会破坏整条链。这是个好习惯。
 * ------------------------------------------------------------------------- */



/* ---------------------------------------------------------------------------
 * 第 3 部分：三个数据结构
 * ------------------------------------------------------------------------- */

/* ---------------------------------------------------------------------------
 * struct nTask —— 一件"活"
 *
 * struct 是"结构体"：把几个不同类型的变量打包成一个整体，
 * 相当于自己动手定义了一种新的数据类型。
 * ------------------------------------------------------------------------- */
struct nTask {
	void (*task_func)(struct nTask *task);
	/*  [★重点] 这是全文件最难的一行：函数指针。
	 *
	 *  拆开读，从里往外看：
	 *    void          —— 这个函数不返回任何值
	 *    (*task_func)  —— 变量名叫 task_func，它是个指针（*），必须加括号
	 *                     （不加括号写成 void *task_func(...) 就变成
	 *                       "返回 void* 的函数声明"了，意思完全不同）
	 *    (struct nTask *task) —— 这个函数接收一个 nTask 指针作为参数
	 *
	 *  合起来：task_func 是一个"指向函数的指针"，它指向的函数长这样：
	 *          void 某个函数名(struct nTask *task)
	 *
	 *  【为什么要用函数指针】
	 *   线程池本身不知道用户想干什么活——可能是算数、可能是发网络包、
	 *   可能是写文件。所以它不写死具体逻辑，只留一个"格子"，
	 *   用户把自己的函数放进去，线程池到时候照着调用。
	 *   这个"留一个格子，你填我调用"的机制，就叫【回调】（callback）。
	 *
	 *  对比一下就很清楚：
	 *    void *user_data;  ← 数据是"什么东西"，用 void* 存
	 *    void (*task_func)  ← 行为是"怎么做"，用函数指针存
	 *  两者合起来，就是一个完整的"待办事项"。
	 */

	void *user_data;
	/*  [★重点] void * 叫"无类型指针"（也叫万能指针）。
	 *  void 意思是"没有类型"，void* 意思是"我暂时不知道指向什么类型"。
	 *  任何类型的指针都能直接赋给 void*，不需要强制转换。
	 *  用它的原因：线程池只管搬运这个指针，不需要知道里面到底是什么。
	 *  用户想装 int 就装 int，想装结构体就装结构体，线程池一概不关心。
	 *  代价：用的时候必须自己强转回正确的类型，转错了编译器不会拦你。
	 *  （本文件下面就有强转的例子：*(int *)task->user_data）
	 */

	struct nTask *prev;
	struct nTask *next;
	/*  把链表节点直接做在任务结构体里，不给它单独分配节点。
	 *  这个技巧叫【侵入式链表】（intrusive list）：
	 *  省一次 malloc，也省一次 free。
	 *  代价是：这个任务一旦挂进链表，用户就不能再随便动它的 prev/next 了。
	 */
};


/* ---------------------------------------------------------------------------
 * struct nWorker —— 一个"工人"（也就是一条真正的线程）
 *
 * 注意：这个结构体只是"工人的身份证"，真正干活的代码在 nThreadPoolCallback 里。
 * ------------------------------------------------------------------------- */
struct nWorker {
	pthread_t threadid;
	/* 线程的"身份证号"。pthread_create 成功后会把号码写进这里。
	 * 以后想控制这条线程（比如等它结束），就靠这个号码找它。
	 * pthread_t 具体是什么类型，不同系统不一样，不要假设它是整数。
	 */

	int terminate;
	/*  "要不要下班"的标志位，0 = 继续干，非 0 = 该收工了。
	 *  这是线程之间传递"停止命令"的最简单办法：
	 *  别的线程改这个变量，工人每次循环开头看一眼。
	 *  ⚠️ 注意：普通 int 在严格意义上跨线程读写不是原子的，
	 *     正规做法要用 stdatomic.h 的原子变量。教学代码里先这么用。
	 */

	struct nManager *manager;
	/*  指回"经理"。为什么需要这个？
	 *  因为工人的循环函数只拿到一个参数（它自己），
	 *  但要找任务，得去经理身上的 tasks 链表里找。
	 *  所以必须能从"我"走到"我的经理"。这条反指的线不能少。
	 *  注意这里写了 struct nManager *，而 nManager 的定义在下面——
	 *  C 里像这样"先声明我用的是个结构体指针"是允许的，
	 *  因为编译器此时只需要知道"有这么一个名字"，不需要知道它多大。
	 */

	struct nWorker *prev;
	struct nWorker *next;
	/*  工人同样用侵入式链表串起来，方便统一管理（比如全部通知下班）。 */
};


/* ---------------------------------------------------------------------------
 * typedef struct nManager { ... } ThreadPool;  —— 经理
 *
 * typedef 的作用是"给一个已有类型起个新名字"。
 * 这里的写法有个小技巧：
 *   struct nManager { ... }  定义了结构体，它的正式类型名是 struct nManager
 *   typedef ... ThreadPool;  又给它起了个简称 ThreadPool
 * 于是 struct nManager 和 ThreadPool 指的是同一个东西，用哪个都行。
 * 起简称是为了后面写起来短一点、也更好懂。
 * ------------------------------------------------------------------------- */
typedef struct nManager {
	struct nTask *tasks;
	/*  任务链表的头。永远指向"最上面那个任务"。
	 *  因为是插在头部，所以这里其实是"栈顶"：最后放进去的任务最先被取走
	 *  （后进先出 LIFO）。想改成先进先出（队列），就得插到尾部，还要多维护尾巴指针。
	 */

	struct nWorker *workers;
	/*  工人链表的头。创建线程时就往里插，这里是"员工名册"。 */

	pthread_mutex_t mutex;
	/*  [★重点] 互斥锁（mutex = mutual exclusion，"互相排斥"）。
	 *
	 *  【它解决什么问题】
	 *    多条线程同时改同一份数据会出乱子。
	 *    比如链表插入，A 线程刚把新节点的 next 指好、还没改链表头，
	 *    B 线程就已经在读了，它看到的是一份"半成品"，程序就崩了。
	 *    这种"多个线程抢同一份数据、结果取决于谁先谁后"的情况叫【竞态条件】
	 *    （race condition），是并发编程的头号敌人。
	 *
	 *  【它怎么解决】
	 *    把它想成洗手间门上的锁：进去的人把门锁上（lock），
	 *    别人只能在门口排队等（阻塞）；里面的人出来开锁（unlock），
	 *    下一个人才能进去。任何时刻最多一个人能进去，所以那份数据始终是完整的。
	 *
	 *  【最关键的一条规矩】
	 *    锁保护的是【数据】，不是【代码】。
	 *    凡是访问 tasks / workers 这两条链表的地方，都必须先拿到这把锁。
	 *    少lock一处，等于门白装了。
	 */

	pthread_cond_t cond;
	/*  [★重点] 条件变量（condition variable，"条件"+"变量"）。
	 *
	 *  【它解决什么问题】
	 *    工人发现没任务了，该怎么办？
	 *    错误做法：写个 while(没任务) { } 一直空转。
	 *      → 这叫"忙等待"，白白烧掉一个 CPU 核心，纯浪费电。
	 *    正确做法：跟操作系统说"我先睡了，有任务你再叫我"。
	 *      条件变量就是这张"床 + 叫醒服务"。
	 *
	 *  【它和锁的配合，是整份代码最精妙的地方】
	 *    条件变量不能单独用，必须和某一把锁配对，
	 *    因为"判断条件（有没有任务）"和"睡觉"这两件事必须是一气呵成的，
	 *    中间不能被人插队——否则会漏掉通知，这个坑下面 pthread_cond_wait 处细讲。
	 *
	 *  【它管什么"条件"】
	 *    这里管的条件只有一个：任务链表是不是空的。
	 *    注意：条件变量本身【不记录】条件成立没有。
	 *    它只是个"集合点"：谁想等就睡在这里，谁发现条件变了就喊一嗓子。
	 *    条件到底成立没有，得靠工人自己醒来后再看一眼链表——这就是下面
	 *    那个 while 循环存在的全部理由。
	 */
} ThreadPool;



/* ---------------------------------------------------------------------------
 * 第 4 部分：工人的工作循环 —— 整份代码的心脏
 * ------------------------------------------------------------------------- */

/* callback != task
 * 这句原作者的注释是在提醒：别把"工人线程的运行函数"和"用户提交的任务函数"搞混。
 *   nThreadPoolCallback —— 每条线程从生到死只跑这一个函数，里面是个死循环
 *   task_entry          —— 用户提交的活，跑完就结束
 * 两者签名长得像（都收一个指针、都可能返回 void*），但角色完全不同。
 */
static void *nThreadPoolCallback(void *arg) {
/*  逐部分读这个函数签名：
 *    static —— 这个函数只在【本文件】内可见，别的 .c 文件链接不到它。
 *              相当于 C 里的"私有函数"，是个好习惯。
 *    void * —— 返回值是万能指针。这是 pthread 规定的格式，不能改。
 *    (void *arg) —— 参数也是万能指针。pthread_create 时传进来什么，
 *                   这里就收到什么。本代码里传的是 nWorker*。
 */

	struct nWorker *worker = (struct nWorker*)arg;
	/*  [★重点] 把万能指针"还原"回它本来的类型。
	 *  括号里 (struct nWorker*) 是【强制类型转换】（cast）：
	 *  "我知道这块内存其实是个 nWorker，请按 nWorker 来解释它"。
	 *  为什么能这么干？因为创建线程时传进去的就是 nWorker*（见第 109 行），
	 *  类型对得上，指针的数值也没变，只是编译器需要你明确告诉它。
	 *  如果这里转成别的类型，编译能过，运行时就是灾难——所以类型一定得自己记住。
	 *  没加参数判空（arg == NULL）检查，这是可以改进的地方。
	 */

	while (1) {
	/*  [★重点] 死循环。工人一生就在这四个步骤里转圈：
	 *     拿锁 → 有活就干 / 没活就睡 → 放锁 → 干活
	 *  循环本身没有退出条件，退出靠的是内部的 break（见后面 terminate 判断）。
	 */

		pthread_mutex_lock(&worker->manager->mutex);
		/*  进门前先锁门。
		 *  & 是"取地址"：把这个变量的内存地址交给函数，函数才能改它。
		 *  worker->manager->mutex 连读两次 -> ：先找到我的经理，再找到经理的锁。
		 *  调用后有两种结果：
		 *    - 锁空着 → 立刻拿到，继续往下走
		 *    - 别人拿着 → 当前线程【阻塞】(卡住不动)，直到对方 unlock
		 *  注意"阻塞"是好事：卡住的线程不占 CPU，操作系统会把它挂起来。
		 */

		while (worker->manager->tasks == NULL) {
		/*  [★重点★] 这里必须是 while，不能写成 if。原因有三层，一层比一层重要：
		 *
		 *  第一层：醒来不等于条件成立。
		 *    被叫醒只是"有人喊了一嗓子"，不代表真有活干。
		 *    比如 20 个工人同时被叫醒，但只来了 1 个任务，
		 *    抢到任务的那个工人拿走了活，另外 19 个醒来一看——链表还是空的。
		 *    所以醒来后必须【重新检查】条件，不成立就接着睡。
		 *
		 *  第二层：操作系统可能"无故"唤醒你（虚假唤醒 spurious wakeup）。
		 *    这不是 bug，是 POSIX 标准明确允许的行为。
		 *    所以任何正经的 pthread 代码，cond_wait 都必须包在 while 里。
		 *
		 *  第三层：任务链表是【共享数据】，必须持锁检查。
		 *    此时手里确实拿着锁（上一行刚拿到），所以读到的值是真的。
		 */

			if (worker->terminate) break;
			/*  睡觉之前先看一眼：是不是该下班了？
			 *  如果已经被通知"解散"，就没必要再睡，直接跳出内层 while。
			 *  这次 break 只跳出【内层】这个 while，不是外层死循环。
			 *  所以下面紧接着还要再判一次 terminate，才能跳出外层。
			 *  （C 里 break 永远只跳出"最内层"那一层循环，这点要记牢。）
			 */

			pthread_cond_wait(&worker->manager->cond, &worker->manager->mutex);
			/*  [★重点★] 全文件最核心的一行。它一次性做了三件事，缺一不可：
			 *
			 *  ① 【解锁】先把我手里的 mutex 放开。
			 *     为什么必须放？如果不放，别的线程想 push 任务时会卡在
			 *     pthread_mutex_lock 上——它根本没法把任务放进来，
			 *     也就永远没法叫醒我。那就死锁了，大家都别动。
			 *
			 *  ② 【睡觉】把自己挂到 cond 这个"呼叫集合点"上，然后让出 CPU。
			 *     此时线程完全休眠，不吃 CPU。
			 *
			 *  ③ 【重新加锁】被唤醒后，先把 mutex 重新抢回来，函数才返回。
			 *     所以 pthread_cond_wait 返回时，一定是"手里拿着锁"的状态，
			 *     可以安全地回到 while 顶部再检查一次条件。
			 *
			 *  【为什么必须传两个参数】
			 *    传 cond 是要睡在哪；传 mutex 是要知道该放哪把锁。
			 *    而且①②两步是【原子】的——操作系统保证"解锁"和"挂起"
			 *    中间不会插进任何其他代码，否则就会出现经典的丢通知问题：
			 *      工人：检查没任务 → (此刻别人放了任务并 signal) → 工人才去睡
			 *      → 这一觉没人叫，任务永远躺着，程序卡死。
			 *    第 ① 步的原子性彻底堵死了这个窗口。
			 *
			 *  【这个函数只在 Linux/Unix 上叫这个名字】
			 *    Windows 上对应的函数是 SleepConditionVariableCS。
			 */
		}

		if (worker->terminate) {
		/*  跳出内层 while 后有两条路走到这里：
		 *    a) 上面那个 break 跳出来的（要下班）
		 *    b) 内层 while 条件不成立了（tasks 不空，有活干）
		 *  所以这里必须再判一次：到底是哪种情况？
		 *  这就是为什么上面说"break 只跳出最内层"很关键——单靠一次 break
		 *  没法同时区分这两种情况，只能双层判断。
		 */

			pthread_mutex_unlock(&worker->manager->mutex);
			/*  要走了，先把锁还给别人。
			 *  【铁律】加锁和解锁必须成对出现，而且每一条 return / break 的
			 *  出口路径上都不能漏。漏掉一处，别的线程就永远卡在 lock 上——
			 *  这种 bug 不会报错、不会崩溃，只会"程序突然卡住不走了"，极难查。
			 *  行业惯例：拿到锁之后尽量少写 return。
			 */

			break;
			/*  这次 break 跳出的是【外层】while(1) 死循环。
			 *  工人正式下班，往下走去 free 自己，线程结束。
			 */
		}

		struct nTask *task = worker->manager->tasks;
		/*  走到这里说明真有活了。把链表头那个任务记下来。
		 *  （此时还拿着锁，读到的是准确值。）
		 */

		LIST_REMOVE(task, worker->manager->tasks);
		/*  调用宏把它从链表里摘掉。
		 *  展开后就是前面讲的四步指针操作，"list"被替换成
		 *  worker->manager->tasks，所以链表头也会同步更新。
		 *  【必须在锁里摘】因为有可能两个工人同时看到同一个 task，
		 *  如果都以为自己拿到了、都去执行，同一个任务就被跑了两遍。
		 *  "先摘下来再执行"，让任务在摘掉的瞬间就归属于某一个工人，
		 *  这样天然避免了重复执行。
		 */

		pthread_mutex_unlock(&worker->manager->mutex);
		/*  摘完了，赶紧放锁。
		 *  [★重点] 注意释放锁的位置——它在【执行任务之前】。
		 *  为什么不干脆干完活再放锁？因为那样就退化成"单线程"了：
		 *  20 个工人排成一队，一次只有一个能干活，多线程毫无意义，
		 *  而且还容易死锁。
		 *  【设计原则】锁只保护"读改共享数据"那一小段，越短越好。
		 *  真正耗时的用户任务，绝对不能在持锁状态下跑。
		 *  现在锁已经放掉了，别的工人可以立刻去抢下一个任务，实现并行。
		 */

		task->task_func(task);
		/*  [★重点] 通过函数指针调用用户的任务函数。
		 *  读法：task->task_func 取出那个函数指针，
		 *        后面跟 (task) 就是给它传参数。
		 *  为什么要把 task 自己也传进去？
		 *  因为用户函数只收到这一个参数，它需要从里面拿到 user_data
		 *  （自己的业务数据），甚至可能需要拿到 next 去改链表。
		 *  所以任务函数是"自带上下文"的。
		 *
		 *  这一行是在【没有锁】的状态下执行的，所以：
		 *  好处——多个工人真正并行干活；
		 *  代价——用户函数里如果碰了 pool 的共享数据，必须自己再加锁。
		 *         这一点极易被忽略，也是线程池用错最常见的原因。
		 */
	}

	free(worker);
	/*  循环结束（下班了）才走到这里，把工人的内存还给系统。
	 *  [⚠️ BUG 隐患] 这里让线程"自己把自己 free 掉"是很危险的写法，
	 *  原因有两个：
	 *    1) 此时 pool->workers 链表里还挂着这个节点（或者刚刚被置空），
	 *       如果别的地方还去走这个链表，踩到的就是已经释放的内存（野指针）。
	 *    2) 主线程如果想 join 这条线程，得先读 worker->threadid，
	 *       但内存可能已经被这条线程自己释放了——读到的是垃圾数据。
	 *  正规做法：谁创建谁释放。由主线程 join 之后再统一 free。
	 *  （修正版 threadpool_win32.c 就是这么改的。）
	 */

}
/*  [⚠️ BUG] 函数声明了返回 void*，但这里没有写 return。
 *  C 语言规定：非 void 返回类型的函数走到末尾而没 return，
 *  拿到的返回值是"未定义"的。
 *  在 pthread 里，这个返回值会被 pthread_join 的第二个参数取走，
 *  写个 return NULL; 才是正确做法，也是消除编译器警告的必需项。 */



/* ---------------------------------------------------------------------------
 * 第 5 部分：对外提供的三个 API
 *
 * 所谓 API（Application Programming Interface，应用程序接口），
 * 就是"这个库提供给外面用的函数"。用户只要会用这三个函数，
 * 完全不需要知道里面链表怎么串、锁怎么加。
 * ------------------------------------------------------------------------- */

/* ---------------------------------------------------------------------------
 * nThreadPoolCreate —— 开张：建一个线程池，招 numWorkers 个工人
 * 返回值约定：0 = 成功，负数 = 失败（并且用不同的负数区分失败原因）
 * ------------------------------------------------------------------------- */
int nThreadPoolCreate(ThreadPool *pool, int numWorkers) {

	if (pool == NULL) return -1;
	/*  防御性检查：用户传了个空指针，后面 memset 会直接崩。
	 *  【为什么要做这种检查】因为库是给别人用的，你不能假设调用者是对的。
	 *  让函数"优雅地返回错误码"而不是"直接崩溃"，是库代码的基本素养。 */

	if (numWorkers < 1) numWorkers = 1;
	/*  容错：用户写 0 或负数就当成 1。
	 *  试想如果真是 0，一个工人都没有，任务堆进去就再也不会有人处理了，
	 *  而且 push 的时候 signal 也没人听——任务会永远躺在链表里，
	 *  main 里那句等任务跑完的判断会永远等下去，程序表现得像死机。
	 *  所以这里必须兜底。 */

	memset(pool, 0, sizeof(ThreadPool));
	/*  [★重点] 把 pool 指向的这块内存，全部填成 0。
	 *    pool       —— 要填哪块内存（起始地址）
	 *    0          —— 每个字节填成什么值
	 *    sizeof(ThreadPool) —— 填多少个字节
	 *
	 *  【为什么第一件事就得做这个】
	 *  pool 是 main 里在栈上定义的局部变量，那块内存里是上一个函数留下的垃圾值。
	 *  不清零的话，pool.tasks、pool.workers 就是随机地址，
	 *  后面 while (tasks == NULL) 永远不成立，或者 LIST_INSERT 直接写飞。
	 *  清零之后两条链表自动就是"空链表"（头指针为 NULL），
	 *  这是 C 里"初始化结构体"最常用的手法。
	 *
	 *  ⚠️ 副作用：如果调用方已经把 pool 用起来过，这一行会把之前的
	 *     tasks/workers 指针全部抹掉，造成内存泄漏。所以它只能用在"首次创建"。
	 */

	pthread_cond_t blank_cond = PTHREAD_COND_INITIALIZER;
	memcpy(&pool->cond, &blank_cond, sizeof(pthread_cond_t));
	/*  用"拷贝一个初始化好的样板"的方式初始化条件变量。
	 *
	 *  PTHREAD_COND_INITIALIZER 是 pthread 提供的一个"初始值常量"，
	 *  专门用来在定义变量时直接赋值（因为条件变量内部结构复杂，
	 *  不能简单地写 = 0）。
	 *
	 *  这里干的事，等价于把下面的注释掉的代码放开：
	 *      pthread_cond_init(&pool->cond, NULL);
	 *  也就是说，作者是为了少写两行，绕了个弯：
	 *  先造一个已经初始化好的临时变量 blank_cond，再整块内存复制过去。
	 *
	 *  【为什么不直接用 = 赋值】C 语言里结构体是可以整体赋值的，
	 *  但 PTHREAD_COND_INITIALIZER 在有些平台上是个"花括号列表"，
	 *  不能直接构成赋值表达式的右值，所以用 memcpy 最保险。
	 *
	 *  ⚠️ 提醒：memcpy 只是"按字节复制"，如果条件变量内部含有
	 *     指向自身内部的指针或系统资源句柄，这种复制是危险的。
	 *     在 Linux 的 glibc 上它能正常工作，但这属于"依赖实现细节"的写法。
	 *     更规范的做法就是直接调 pthread_cond_init。 */

	//pthread_mutex_init(&pool->mutex, NULL);
	pthread_mutex_t blank_mutex = PTHREAD_MUTEX_INITIALIZER;
	memcpy(&pool->mutex, &blank_mutex, sizeof(pthread_mutex_t));
	/*  和上面一模一样的手法，这次初始化的是互斥锁。
	 *  PTHREAD_MUTEX_INITIALIZER 是一种"静态初始化"，
	 *  展开后通常是全 0，所以实际上 memset 已经把它清好了，
	 *  但显式写出来更清晰，也不依赖"展开后是全 0"这种假设。
	 *
	 *  【语义上更准确的写法】
	 *  两者效果要区分清楚：
	 *    PTHREAD_MUTEX_INITIALIZER   → 只能用于【定义变量时】，等价于静态初始化
	 *    pthread_mutex_init(...)     → 用于【运行时】，对象是堆上/栈上的已有内存
	 *  本代码是运行时初始化一块已有内存，严格说应该用 pthread_mutex_init
	 *  （也就是被注释掉的那行）。这是原代码一个小瑕疵，功能上通常没问题。
	 */

	int i = 0;
	for (i = 0;i < numWorkers;i ++) {
	/*  循环 numWorkers 次，每次都造一个工人、启动一条线程。
	 *  i 在 for 外面先定义，是老的 C89 风格（变量必须在块的开头声明）。
	 *  现代 C（C99 以后）可以直接写 for (int i = 0; ...)。 */

		struct nWorker *worker = (struct nWorker*)malloc(sizeof(struct nWorker));
		/*  malloc = memory allocate，向操作系统申请一块内存。
		 *    sizeof(struct nWorker) —— 一个工人结构体占多少个字节
		 *  返回的是 void*（万能指针），所以前面强转成 (struct nWorker*)。
		 *  【为什么工人要用 malloc 而不是栈上变量】
		 *  因为栈上变量在函数返回后就失效了，而线程要在函数返回后继续跑很久，
		 *  它需要一份"活得比函数更久"的内存。堆内存（malloc 出来的）
		 *  只有显式 free 才会被回收，正合适。
		 *
		 *  ⚠️ 这里没有为"中途失败"做清理：如果循环到第 10 个 malloc 失败了，
		 *     前面 9 个工人和 9 条线程就被扔在那里没人管了（泄漏）。
		 *     严谨的库代码会写一个 goto cleanup 或专门的销毁逻辑。
		 */

		if (worker == NULL) {
		/*  malloc 失败会返回 NULL，通常是内存真的用光了。
		 *  不检查就直接用，程序会立刻崩在一个毫无线索的地方。 */

			perror("malloc");
			/*  perror = print error。
			 *  它会先打印你给的字符串，然后自动补上"最近一次系统调用
			 *  为什么失败"的原因（比如 "Not enough space"），
			 *  最后加个换行。比自己拼字符串省事得多。
			 *  输出形如：malloc: Not enough space
			 */

			return -2;
		}

		memset(worker, 0, sizeof(struct nWorker));
		/*  把新工人的内存清零。同样是为了让 terminate 变成 0、
		 *  prev/next 变成 NULL，避免带着垃圾值进入链表。
		 *  （其实这里可以换成 calloc，它的作用就是"申请并清零"。）
		 */

		worker->manager = pool; //
		/*  [★重点] 建立"我 → 我的经理"这条反指连线。
		 *  行尾那个 // 是个没写完的空注释，说明作者本来想在这里写点什么。
		 *
		 *  为什么必须有这一句？因为等下传给线程的参数只有 worker 自己，
		 *  而工人要干活必须能找到 tasks 链表，tasks 在经理身上。
		 *  没有这条线，工人在回调函数里就完全"失忆"了，找不到任务。
		 */

		int ret = pthread_create(&worker->threadid, NULL, nThreadPoolCallback, worker);
		/*  [★重点] 创建线程。一句话让操作系统多跑一条执行流。
		 *
		 *  四个参数逐个拆：
		 *    &worker->threadid
		 *        输出参数。线程创建成功后，系统把线程 ID 写到这块内存里。
		 *        必须传地址，因为函数要"写回来"。
		 *
		 *    NULL
		 *        线程属性。传 NULL 表示"用默认属性"（默认就是可汇合的、非分离的）。
		 *        想改栈大小、想设成分离线程（detached），就从这里传 pthread_attr_t。
		 *
		 *    nThreadPoolCallback
		 *        新线程要执行的函数。注意这里写的是【函数名】，
		 *        不加括号——加括号就变成"调用它并把返回值传进去"了。
		 *        在这里函数名会自动退化成函数指针，正是 task_func 那种类型。
		 *
		 *    worker
		 *        传给新线程的参数。新线程会在自己的函数里
		 *        用 void *arg 接到这个值（见第 58 行的强转）。
		 *
		 *  【关键性质】pthread_create 是"异步"的——它立刻返回，
		 *  新线程什么时候开始跑、跑到哪儿了，你完全不知道。
		 *  上一行还在给 worker 赋值，下一行新线程可能已经在读它了。
		 *  所以这里必须保证：worker 的所有字段在 pthread_create 之前就填好。
		 *  本代码顺序是对的（先 memset、先赋 manager，再 create）。
		 */

		if (ret) {
		/*  pthread 系列函数的返回值约定和一般 C 函数不同：
		 *  它不用 errno，而是直接把错误码当返回值返回，
		 *  0 表示成功，非 0 表示失败。
		 *  所以这里 if (ret) 就是"ret 不等于 0"的意思（C 里非 0 即真）。 */

			perror("pthread_create");
			/*  ⚠️ 小提示：这里用 perror 其实不严谨。
			 *  perror 读的是全局变量 errno，而 pthread 的错误码是
			 *  直接从返回值给的，没有写进 errno。
			 *  所以这行打印出来的原因可能是不相干的旧错误。
			 *  正确写法：printf("pthread_create failed: %s\n", strerror(ret));
			 *  strerror 能把错误码翻译成人话。 */

			free(worker);
			/*  线程没建起来，这份内存也没人用了，赶紧还回去。 */

			return -3;
			/*  ⚠️ 同样的问题：已经成功的那些线程和 worker 没被清理，
			 *     属于资源泄漏。调用者拿到 -3 也没法知道该清理什么。
			 *     这暴露了一个设计问题：创建失败时应该做"回滚"。 */
		}

		LIST_INSERT(worker, pool->workers);
		/*  把新工人挂到经理的员工名册上。
		 *  宏展开后 pool->workers 会指向这个新工人，原来的名册整体后移一格。
		 *  插在头部，所以名册里顺序和创建顺序是反的（最后创建的排最前），
		 *  这里无所谓，因为遍历时每个都会被处理。
		 *
		 *  ⚠️ 顺序提醒：这一句在 pthread_create 【之后】。
		 *     理论上存在一个极小的时间窗：新线程已经开始跑，但名册还没记上它。
		 *     对本代码无害（工人不会去遍历名册），但如果将来在回调里
		 *     依赖"能在名册里找到自己"，就会踩坑。
		 *     稳妥做法是把 LIST_INSERT 挪到 pthread_create 之前。
		 */
	}

	// success
	return 0;
	/*  返回 0 表示全部创建成功。 */

}



/* ---------------------------------------------------------------------------
 * nThreadPoolDestory —— 关张：通知所有工人下班，销毁线程池
 * （函数名拼错了，destroy 少了个 e，不过这不算错，只是不好看。
 *   一旦被别的代码调用，改名就会破坏兼容性，所以现实中的库经常将错就错。）
 * ------------------------------------------------------------------------- */
int nThreadPoolDestory(ThreadPool *pool, int nWorker) {

	struct nWorker *worker = NULL;

	for (worker = pool->workers;worker != NULL;worker = worker->next) {
	/*  遍历员工名册，准备一个个通知。
	 *    worker = pool->workers  —— 从头开始
	 *    worker != NULL          —— 还没走完（链表尾的 next 是 NULL）
	 *    worker = worker->next   —— 走到下一个
	 *
	 *  ⚠️⚠️ 这里有个隐患：循环体里一旦改动链表（比如摘除节点），
	 *      提前取好的 worker->next 就可能已经失效。
	 *      安全写法是先存下来：struct nWorker *next = worker->next;
	 *      再用 next 前进。本循环体没改链表，所以侥幸没出事。
	 */

		worker->terminate;
		/*  [⚠️⚠️ 严重 BUG] 这一行什么也没做！
		 *
		 *  它只是"取出 terminate 的值，然后丢掉"，等价于一句废话。
		 *
		 *  【实测结论，比想象的更糟】
		 *    本机用 MSVC 2019 分别以 /W3 和 /W4 编译这一行，
		 *    结果【一个警告都没有】，编译器完全不作声。
		 *    （GCC 需要显式加 -Wall 才可能提示 "statement has no effect"， 
		 *      而 -Wall 并不是默认开启的。）
		 *
		 *    为什么会这样？因为语法上它完全合法——它是一个"表达式语句"，
		 *    就像单独写一句 x; 一样。编译器不知道该不该容忍，
		 *    通常干脆不管。
		 *
		 *    这就意味着：这类 bug 既不会编译报错、也不会运行时崩溃，
		 *    只会让功能静悄悄地失效。它比段错误难查得多，
		 *    因为段错误至少会告诉你"这里出事了"。
		 *
		 *  作者的本意显然是：
		 *      worker->terminate = 1;      ← 少写了一个 = 1
		 *
		 *  【后果有多严重】
		 *  所有工人的 terminate 永远是 0，第 64 行那句
		 *      if (worker->terminate) break;
		 *  永远不成立，工人永远不会下班。整个销毁流程形同虚设。
		 *
		 *  【为什么程序看起来还是"正常结束"了】
		 *  因为 main 走到 getchar() 之后返回，进程整体退出，
		 *  操作系统会把进程里所有线程一起强制干掉。
		 *  也就是说：线程不是被"优雅地请走"的，而是被"连锅端"的。
		 *  在这种玩具程序里看不出问题，一旦放到真实服务里
		 *  （比如线程正在写文件、发网络包的时候被强杀），
		 *  就会留下写了一半的脏数据、没来得及关闭的连接。
		 *
		 *  【这类错误的可怕之处】
		 *  代码能编译、能跑、看不出任何异常，编译器连警告都不给。
		 *  唯一的发现途径是【真的去运行它，并验证结果】——
		 *  这恰恰是这份代码最该反思的地方：
		 *  main 里压根没调用过 destory，
		 *  所以这段销毁逻辑从来没有被执行过一次，bug 也就一直藏着。
		 *  写代码时最值得做的一件事，就是让每一行都至少被跑过一次。
		 */
	}

	pthread_mutex_lock(&pool->mutex);
	/*  要发通知了，先拿锁。
	 *  为什么要拿？不是为了保护链表，而是为了和工人的 pthread_cond_wait
	 *  "对齐时序"：拿到锁说明此刻没有工人正卡在"判断条件"和"去睡"之间，
	 *  这样我们的广播就不会被漏掉。 */

	pthread_cond_broadcast(&pool->cond);
	/*  [★重点] 广播：叫醒【所有】睡在这张 cond 上的工人。
	 *
	 *  对比一下两个函数：
	 *    pthread_cond_signal      —— 只叫醒一个（用于"来活了，一个人去接"）
	 *    pthread_cond_broadcast   —— 叫醒全部（用于"条件整体变了，大家都醒醒"）
	 *
	 *  为什么这里必须用 broadcast 而不能用 signal？
	 *  因为 terminate 是"全局下岗通知"，不是"有一个任务"。
	 *  如果只叫醒一个，剩下 19 个会一直睡着，
	 *  线程池就永远销毁不干净。这是个非常典型的选错函数的场景。 */

	pthread_mutex_unlock(&pool->mutex);
	/*  发完通知放锁。工人被唤醒后会自己再去抢锁，然后重新判断条件。 */

	pool->workers = NULL;
	pool->tasks = NULL;
	/*  把两个链表头置空，让这个 pool 结构看起来像"空的"。
	 *
	 *  ⚠️⚠️ [严重设计缺陷] 这两行只是【抹掉指针】，并没有：
	 *     1) pthread_join 等待线程真正结束
	 *     2) free 掉 workers 链表里剩下的节点
	 *     3) free 掉 tasks 链表里还没执行的任务
	 *
	 *  于是：
	 *    - 工人在回调结尾自己 free(worker)，但主线程手里的链表结点
	 *      在被置 NULL 之前还指向这些内存，属于"野指针"现场。
	 *    - 还没执行完的任务全部泄漏。如果任务里也 malloc 了东西，
	 *      那些也一起泄漏。
	 *    - 最要命的是"线程还活着，主线程以为已经清干净了"，
	 *      这在真实程序里会导致 release 之后 use-after-free，随机崩溃、
	 *      而且崩的位置和真正出错的代码离得很远，极难排查。
	 *
	 *  【正确的销毁顺序应该是】
	 *    1. 加锁 → 把所有 worker->terminate 置 1 → 解锁
	 *    2. broadcast 唤醒全部
	 *    3. 遍历 workers，对每个执行 pthread_join 等它真正结束
	 *       （join 之后才能保证线程不再碰这块内存）
	 *    4. join 完再 free 每个 worker 节点
	 *    5. 清理 tasks 链表里剩余的、没跑完的任务
	 */

	return 0;
	/*  返回成功。
	 *  ⚠️ 参数 nWorker 从头到尾没用过，是个多余的参数。
	 *     本来可能是想指定"只销毁前 n 个"之类的功能，没写完。 */

}



/* ---------------------------------------------------------------------------
 * nThreadPoolPushTask —— 提交一件活
 * 这是用户最常调用的函数：把任务丢进去，然后立刻返回，不等它做完。
 * ------------------------------------------------------------------------- */
int nThreadPoolPushTask(ThreadPool *pool, struct nTask *task) {

	pthread_mutex_lock(&pool->mutex);
	/*  拿锁。因为要改共享数据 tasks 链表，改之前必须锁门。 */

	LIST_INSERT(task, pool->tasks);
	/*  把任务插到链表头部。宏展开后 pool->tasks 指向这个新任务。
	 *  因为插在头、工人也从头部取，所以其实是"栈"：
	 *  最后提交的任务会被最先执行。
	 *  结果就是 main 里推 0..999，实际执行顺序大致是 999, 998, ... 0。
	 *  （实际顺序还会被多线程打乱，但趋势是倒着的。）
	 *  这在有些场景是问题（比如要求保序），就需要改成插到尾部。 */

	pthread_cond_signal(&pool->cond);
	/*  [★重点] 叫醒一个正在睡觉的工人：快来，有活了！
	 *
	 *  为什么是 signal 而不是 broadcast？
	 *  因为只多了一个任务，理论上只需要一个人来处理。
	 *  叫醒全部是浪费——19 个人被唤醒后抢不到活，还得再睡回去，
	 *  这叫【惊群效应】（thundering herd），会白白增加系统开销。
	 *
	 *  ⚠️ 这里有个容易被忽略的细节：这一行是在【持锁状态】下执行的。
	 *     这不是错误，反而是安全的做法——
	 *     持锁发通知可以确保"改链表"和"发通知"是原子的，
	 *     不会有工人卡在"检查到链表为空"和"真正睡下去"之间漏掉通知。
	 *     （代价是被唤醒的工人醒来后要先等一下锁，但这个开销很小。
	 *       另一种写法是"持锁改数据、放锁再 signal"，性能略好，
	 *       但要求非常小心地推理时序，新手不建议。）
	 */

	pthread_mutex_unlock(&pool->mutex);
	/*  放锁。任务已经安全挂上链表了，可以放别的线程进去。 */

}
/*  [⚠️ BUG] 函数声明为返回 int，但没有任何 return 语句。
 *  调用方拿到的会是垃圾值。
 *  应该补一句 return 0;（并且在 pool 或 task 为空时提前 return -1）。
 *
 *  【另一个可以改进的点】本函数没有做参数校验：
 *  如果 task 为 NULL，LIST_INSERT 展开后第一步就是 item->prev = NULL，
 *  对空指针写入 → 进程当场崩溃，而且崩在宏里面，堆栈看起来莫名其妙。 */



